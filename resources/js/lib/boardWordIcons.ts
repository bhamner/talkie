export function boardWordShowsLetterOnly(label: string): boolean {
    return boardWordLetterOnlyLabels.has(label.trim().toLowerCase());
}

export function boardWordLetterDisplay(label: string): string {
    return label.trim().charAt(0).toUpperCase();
}

export function boardWordIcon(label: string): BoardWordIconData | undefined {
    return boardWordIconMap[label.trim().toLowerCase()];
}

export function boardWordIconSizeAdjustment(label: string): number {
    return boardWordIconSizeAdjustments[label.trim().toLowerCase()] ?? 0;
}

export function boardWordColor(label: string): string | undefined {
    return boardWordColorMap[label.trim().toLowerCase()];
}
